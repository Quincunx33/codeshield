import AdmZip from "adm-zip";

const base = process.env.CODESHIELD_SERVER ?? "http://127.0.0.1:3000/api/trpc";
const zip = new AdmZip();
const samples = [
  ["src/main.py", "def add(a, b):\n    return a + b"],
  ["src/unsafe.c", "void run(char *cmd) { system(cmd); }"],
  ["src/App.tsx", "// Here is a robust implementation\n// Generated by an assistant\n// TODO: make robust\nexport function App() { return <div />; }"],
  ["src/duplicate-a.ts", `const repeatedWorkflow = "${"stable reusable workflow data ".repeat(8)}";`],
  ["src/duplicate-b.ts", `const repeatedWorkflow = "${"stable reusable workflow data ".repeat(8)}";`],
  ["docs/comment.py", "# eval(user_input)\n# system(user_input)"],
];
for (const [path, content] of samples) zip.addFile(path, Buffer.from(content));
const archiveBase64 = zip.toBuffer().toString("base64");
const payload = { json: { projectName: "small-file-api-stress", files: [], archiveBase64, archiveName: "small-file-stress.zip" } };

async function scan(index) {
  const response = await fetch(`${base}/scanner.run`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(payload) });
  const body = await response.json();
  if (!response.ok || body.error) throw new Error(`request ${index} failed: ${response.status} ${JSON.stringify(body).slice(0, 300)}`);
  const report = body.result?.data?.json ?? body;
  if (report.filesScanned !== samples.length || !report.qualityScore || !Array.isArray(report.findings) || !Array.isArray(report.aiSignals)) throw new Error(`request ${index} returned an invalid report contract`);
  if (!report.findings.some((finding) => finding.ruleId === "SECSHE" || finding.title === "Shell command execution")) throw new Error(`request ${index} lost the intentional C true positive`);
  if (report.findings.some((finding) => finding.file === "docs/comment.py" && finding.category === "security")) throw new Error(`request ${index} raised a commented-code false positive`);
  return report;
}

const started = Date.now();
const reports = await Promise.all(Array.from({ length: 40 }, (_, index) => scan(index)));
const first = JSON.stringify({ findings: reports[0].findings, summary: reports[0].summary, qualityScore: reports[0].qualityScore, aiSignals: reports[0].aiSignals });
for (const report of reports.slice(1)) {
  const current = JSON.stringify({ findings: report.findings, summary: report.summary, qualityScore: report.qualityScore, aiSignals: report.aiSignals });
  if (current !== first) throw new Error("concurrent reports were not deterministic");
}
console.log(JSON.stringify({ requests: reports.length, filesPerArchive: samples.length, stable: true, elapsedMs: Date.now() - started, findingCount: reports[0].findings.length, qualityScore: reports[0].qualityScore.score, aiSignals: reports[0].aiSignals.length }, null, 2));
